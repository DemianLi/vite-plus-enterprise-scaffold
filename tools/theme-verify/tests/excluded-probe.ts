/**
 * 反向探針：一個**應該掃不到**的類別。
 *
 * ── 它與 `fixtures/probe.ts` 是一對，方向相反 ──────────────────────
 *
 *   fixtures/probe.ts   `.ts` 裡的類別**必須**進產物（覆寫字串住在 .ts）
 *   這一份              `tests/` 裡的類別**不准**進產物
 *
 * ── 為什麼需要它 ───────────────────────────────────────────────────
 *
 * Tailwind 的抽取器**不解析語法** —— 它從檔案裡撈長得像 utility 的字串，
 * **連註解裡的都算**。實測（2026-08-19，apps/console）：`platform/ui` 的
 * `@source` 少了 `not` 那兩條排除時，交付的 CSS 多 0.84 kB，13 條選擇器
 * 全部來自測試檔的字面值與註解。
 *
 * ⚠️ **這個字面值必須住在被排除的檔案裡。** 寫在 `src/` 底下的話它自己
 * 就會被掃進產物，那條斷言就永遠是紅的 —— 一個看起來很嚴格、實際上
 * 每次都要有人去 skip 的檢查。所以 `cli.ts` 只 import 變數，不寫字面值。
 *
 * ⚠️ 值要挑一個**任意值**（`[...]`）：它一定合法、一定編得出規則，而且
 * 不可能與任何真的用法撞名。挑 `text-white` 那種真的 utility 會讓斷言
 * 在某天有人真的用了它的時候誤紅。
 */
export const EXCLUDED_PROBE = "pt-[3.7391px]";

/**
 * 在產物裡找它的痕跡時比對的字串。
 *
 * ⚠️ 用**宣告值**而不是選擇器：選擇器在 CSS 裡是 `.pt-\[3\.7391px\]`，
 * 逸出規則是 Tailwind 的實作細節，比對它等於把斷言綁在上游的逸出方式上。
 * 這個數字本身獨一無二，而且它出現在產物裡只有一個可能的來源。
 */
export const EXCLUDED_PROBE_MARK = "3.7391px";
