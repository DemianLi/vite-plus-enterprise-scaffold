const rendered = (current: number, pageCount: number): string =>
  pageRange(current, pageCount)
    .map((item) => (item === ELLIPSIS ? "…" : String(item)))
    .join(" ");

describe("pageRange 與凍結的 reka 答案逐組相同", () => {
  it("★ 表真的有 210 組 —— 否則下面是在少數幾組上綠", () => {
    expect(Object.values(EXPECTED).flat()).toHaveLength(210);
  });

  it.each(
    Object.entries(EXPECTED).flatMap(([pageCount, pages]) =>
      pages.map((expected, index) => [Number(pageCount), index + 1, expected] as const),
    ),
  )("%i 頁、第 %i 頁 → %s", (pageCount, current, expected) => {
    expect(rendered(current, pageCount)).toBe(expected);
  });

  it("🔴 表對得出錯：鄰居數改成 1，至少有一組不同", () => {
    const differs = Object.entries(EXPECTED).some(([pageCount, pages]) =>
      pages.some(
        (expected, index) =>
          pageRange(index + 1, Number(pageCount), 1)
            .map((item) => (item === ELLIPSIS ? "…" : String(item)))
            .join(" ") !== expected,
      ),
    );
    expect(differs).toBe(true);
  });
});
